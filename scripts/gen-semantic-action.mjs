// Generate ts/src/semantic-action-data.ts (the embedded SemanticAction contract the engine ships)
// from the vendored ontology/semantic-action/SemanticAction.json. Run with plain node:
//   node scripts/gen-semantic-action.mjs
// The engine bundles to a single file per format (tsup), so there is no runtime asset to read —
// the schema ships embedded exactly as KKO does. Commit both the .json and the regenerated
// semantic-action-data.ts after re-vendoring from sourceos-spec.
import { readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'

const jsonPath = fileURLToPath(new URL('../ontology/semantic-action/SemanticAction.json', import.meta.url))
const outPath = fileURLToPath(new URL('../ts/src/semantic-action-data.ts', import.meta.url))

// Hash the RAW BYTES (trailing newline included) so the pinned digest equals the upstream file's.
const bytes = readFileSync(jsonPath)
const sha256 = createHash('sha256').update(bytes).digest('hex')
const text = bytes.toString('utf8')
const schema = JSON.parse(text) // parse-check: never embed something that is not valid JSON

const out = `// GENERATED by scripts/gen-semantic-action.mjs from ontology/semantic-action/SemanticAction.json
// — do not edit by hand. SemanticAction ${schema.properties.specVersion.const} · ${bytes.length} bytes.
// Provenance (see ontology/semantic-action/PROVENANCE.md):
//   repo    SourceOS-Linux/sourceos-spec (merged PR #210)
//   path    schemas/SemanticAction.json
//   commit  ee7e43a42d5b3c30897eee296832ca127e8f6099
//           (2026-07-29, "schemas: KnowledgeNugget + SemanticAction v0.1 — L2 content grain +
//            typed-action registry")
//   sha256  ${sha256}
// The digest is asserted at import by ts/src/nlq.ts: a drifted or hand-edited copy fails LOUDLY at
// load, never silently at declareAction time.

/** The vendored SemanticAction JSON Schema, verbatim (raw upstream bytes, trailing newline included). */
export const SEMANTIC_ACTION_SCHEMA_TEXT = ${JSON.stringify(text)}

/** SHA-256 over the raw upstream bytes of SemanticAction.json. Pinned — asserted at import. */
export const SEMANTIC_ACTION_SCHEMA_SHA256 = ${JSON.stringify(sha256)}

/** The \`specVersion\` const the contract pins. Changing it upstream is a contract change. */
export const SEMANTIC_ACTION_SPEC_VERSION = ${JSON.stringify(schema.properties.specVersion.const)}
`

writeFileSync(outPath, out)
console.log(`wrote ${outPath}\n  bytes  ${bytes.length}\n  sha256 ${sha256}\n  spec   ${schema.properties.specVersion.const}`)
