// Generate ts/src/effect-request-data.ts (the embedded EffectRequest contract the engine ships)
// from the vendored ontology/effect-request/EffectRequest.json. Run with plain node:
//   node scripts/gen-effect-request.mjs
// The engine bundles to a single file per format (tsup), so there is no runtime asset to read —
// the schema ships embedded exactly as KKO and SemanticAction do. Commit both the .json and the
// regenerated effect-request-data.ts after re-vendoring from sourceos-spec.
//
// Mirrors scripts/gen-semantic-action.mjs deliberately: the vendor-freshness plane the generated
// contract serves is itself subject to the discipline it enforces, so the two vendored contracts
// are vendored the same way.
import { readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'

const jsonPath = fileURLToPath(new URL('../ontology/effect-request/EffectRequest.json', import.meta.url))
const outPath = fileURLToPath(new URL('../ts/src/effect-request-data.ts', import.meta.url))

// Hash the RAW BYTES (trailing newline included) so the pinned digest equals the upstream file's.
const bytes = readFileSync(jsonPath)
const sha256 = createHash('sha256').update(bytes).digest('hex')
const text = bytes.toString('utf8')
const schema = JSON.parse(text) // parse-check: never embed something that is not valid JSON

const out = `// GENERATED by scripts/gen-effect-request.mjs from ontology/effect-request/EffectRequest.json
// — do not edit by hand. EffectRequest ${schema.properties.specVersion.const} · ${bytes.length} bytes.
// Provenance (see ontology/effect-request/PROVENANCE.md):
//   repo    SourceOS-Linux/sourceos-spec (merged PR #204)
//   path    schemas/EffectRequest.json
//   commit  487e4b614b79e556af3aea2c70471eca13281377
//           (2026-07-28, "schemas: MPCC event contract v0.1 — conversation + trading event family")
//   sha256  ${sha256}
// The digest is asserted at import by ts/src/vendor-graph.ts: a drifted or hand-edited copy fails
// LOUDLY at load, never silently when a re-vendor proposal is emitted.

/** The vendored EffectRequest JSON Schema, verbatim (raw upstream bytes, trailing newline included). */
export const EFFECT_REQUEST_SCHEMA_TEXT = ${JSON.stringify(text)}

/** SHA-256 over the raw upstream bytes of EffectRequest.json. Pinned — asserted at import. */
export const EFFECT_REQUEST_SCHEMA_SHA256 = ${JSON.stringify(sha256)}

/** The \`specVersion\` const the contract pins. Changing it upstream is a contract change. */
export const EFFECT_REQUEST_SPEC_VERSION = ${JSON.stringify(schema.properties.specVersion.const)}
`

writeFileSync(outPath, out)
console.log(`wrote ${outPath}\n  bytes  ${bytes.length}\n  sha256 ${sha256}\n  spec   ${schema.properties.specVersion.const}`)
